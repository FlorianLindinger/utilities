"use strict";

const crypto = require("node:crypto");

const LABELS = Object.freeze({
  off: "Off",
  basic: "Basic",
  default: "Default",
  strict: "Strict",
  local: "Local",
  custom: "Custom",
});
const EXPLICIT_MODES = ["basic", "default", "strict", "custom"];

function folderId(uri) {
  return crypto.createHash("sha256").update(uri).digest("hex").slice(0, 24);
}

function sourcePatterns(folderPath) {
  const root = folderPath.replace(/\\/g, "/").replace(/\/+$/, "");
  const roots = new Set([root]);
  if (/^[a-z]:/i.test(root)) {
    roots.add(root[0].toLowerCase() + root.slice(1));
    roots.add(root[0].toUpperCase() + root.slice(1));
  }
  const literal = (value) => value.replace(/[?*\[\]{}]/g, (c) => `[${c}]`);
  return [...roots].flatMap((value) =>
    ["py", "pyi", "pyw", "ipynb"].map((suffix) => `${literal(value)}/**/*.${suffix}`),
  );
}

function buildConfig(mode, folderPath, customPath) {
  if (!EXPLICIT_MODES.includes(mode)) throw new Error(`Unknown explicit mode: ${mode}`);
  const quote = (value) => JSON.stringify(value.replace(/\\/g, "/"));
  const lines = ["# Generated by Local Pyrefly Profile Switcher; edit shared rules instead."];
  if (mode === "custom") {
    if (!customPath) throw new Error("Set pyreflyProfiles.customConfigPath first.");
    lines.push(`extends = ${quote(customPath)}`);
  } else {
    lines.push(`preset = ${JSON.stringify(mode)}`);
  }
  lines.push(`import-root = ${quote(folderPath)}`, "project-includes = [");
  for (const pattern of sourcePatterns(folderPath)) lines.push(`    ${JSON.stringify(pattern)},`);
  lines.push("]", "");
  return lines.join("\n");
}

module.exports = { LABELS, EXPLICIT_MODES, folderId, sourcePatterns, buildConfig };
